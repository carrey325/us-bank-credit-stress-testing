from pathlib import Path

import pandas as pd
import pytest

from bankstress.r3 import (
    _rearrange, assert_not_cumulative_q90, prediction_target_dictionary,
    predict_quantile, quarter_sequence, validate_target_dictionary,
)


def test_prediction_targets_and_nominal_labels_are_distinct():
    rows = prediction_target_dictionary()
    validate_target_dictionary(rows)
    indexed = {row["target_id"]: row for row in rows}
    assert indexed["one_step_q90_upper_quantile"]["nominal_exceedance_rate"] == 0.10
    assert indexed["one_step_q50_q90_band"]["nominal_coverage"] == 0.40
    assert indexed["residual_calibrated_two_sided_90_interval"]["status"] == "NOT_EVALUATED"
    assert indexed["multi_period_cumulative_loss_q90"]["status"] == "NOT_EVALUATED"


def test_quantile_crossing_is_counted_and_raw_predictions_are_preserved():
    base = pd.DataFrame({"bank_id": ["1"], "segment": ["CRE"], "forecast_origin": [pd.Timestamp("2020-02-15")],
                         "target_period": [pd.Timestamp("2020-03-31")], "nco_rate": [0.2]})
    frames = {}
    for tau, value in [(0.5, 0.3), (0.75, 0.2), (0.9, 0.4)]:
        frames[tau] = base.assign(prediction_raw=value)
    repaired, count = _rearrange(frames)
    assert count == 1
    assert repaired[0.5].prediction_raw.iloc[0] == 0.3
    assert [repaired[t].prediction_rearranged.iloc[0] for t in sorted(repaired)] == [0.2, 0.3, 0.4]


def test_actual_exceedance_count_is_not_a_coverage_proxy():
    actual = pd.Series([0.0, 2.0, 3.0])
    prediction = pd.Series([1.0, 1.0, 4.0])
    assert int((actual > prediction).sum()) == 1
    assert float((actual > prediction).mean()) == pytest.approx(1 / 3)


def test_quarter_block_boundaries_are_complete():
    quarters = quarter_sequence(pd.Timestamp("2007-01-01"), pd.Timestamp("2010-12-31"))
    assert len(quarters) == 16
    assert quarters[0] == pd.Timestamp("2007-03-31")
    assert quarters[-1] == pd.Timestamp("2010-12-31")


def test_fixed_q90_feedback_cannot_be_labelled_cumulative_q90():
    assert_not_cumulative_q90("recursive_quantile_sensitivity_not_distribution")
    with pytest.raises(ValueError, match="sensitivity"):
        assert_not_cumulative_q90("multi_period_cumulative_loss_q90")


def test_generated_artifacts_preserve_paths_when_realized_values_are_missing():
    path = Path(__file__).resolve().parents[1] / "outputs/repair/r3/validation_summary.json"
    if not path.exists():
        pytest.skip("R3 artifact is generated by scripts/run_r3.py")
    summary = pd.read_json(path, typ="series")
    assert summary["continuous_path_row_count"] == summary["expected_continuous_path_row_count"]
    assert summary["paths_preserved_with_missing_actual"] > 0
    assert summary["future_control_leakage_count"] == 0
    paths = pd.read_parquet(path.parents[2] / "validation/pseudo_stress.parquet")
    window_end = {"GFC": "2006-12-31", "COVID": "2019-12-31", "High_Rate_CRE": "2021-12-31"}
    ends = paths.pseudo_window.map(window_end).map(pd.Timestamp)
    assert paths.bank_controls_source_period.le(ends).all()


def test_reported_exceedance_count_matches_saved_actual_predictions():
    root = Path(__file__).resolve().parents[1]
    predictions_path = root / "outputs/validation/oos_predictions.parquet"
    if not predictions_path.exists():
        pytest.skip("R3 artifact is generated by scripts/run_r3.py")
    predictions = pd.read_parquet(predictions_path)
    metrics = pd.read_csv(root / "outputs/validation/tail_metrics.csv")
    selected = predictions[(predictions.window.eq(1)) & (predictions.segment.eq("CRE")) &
                           (predictions.model_family.eq("dynamic_quantile")) & (predictions.tau.eq(0.9)) &
                           (predictions.prediction_version.eq("POST_REARRANGEMENT"))].dropna(subset=["nco_rate"])
    reported = metrics[(metrics.window.astype(str).eq("1")) & (metrics.segment.eq("CRE")) &
                       (metrics.model_family.eq("dynamic_quantile")) & (metrics.tau.eq(0.9)) &
                       (metrics.prediction_version.eq("POST_REARRANGEMENT"))].iloc[0]
    assert reported.exceedance_count == int((selected.nco_rate > selected.prediction).sum())


def test_predict_quantile_does_not_require_realized_target():
    class Result:
        def predict(self, values):
            return [0.1] * len(values)
    from bankstress.r3 import QuantileFit
    fit = QuantileFit(Result(), ["lagged_nco_rate"], ["1", "2"], "1", 0.9, 1, True, None)
    data = pd.DataFrame({"bank_id": ["1"], "segment": ["CRE"], "lagged_nco_rate": [0.2], "nco_rate": [float("nan")]})
    assert len(predict_quantile(fit, data)) == 1
